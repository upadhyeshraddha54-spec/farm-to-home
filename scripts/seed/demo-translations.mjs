/** { hi: { a, b }, mr: { a, b } } from { a: {hi, mr}, b: {hi, mr} }, with the demo note appended to descriptions. */
export function toTranslations(entry) {
  if (!entry) return null
  const result = { hi: {}, mr: {} }
  for (const lang of ['hi', 'mr']) {
    for (const [field, values] of Object.entries(entry)) {
      result[lang][field] =
        field === 'description' ? `${values[lang]}\n\n${DEMO_NOTE_TRANSLATIONS[lang]}` : values[lang]
    }
  }
  return result
}
